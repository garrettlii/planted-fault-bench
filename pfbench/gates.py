"""Acceptance gates for a candidate variant. A variant ships only if every gate passes.

G1  the fault matters    FAULTY: the naive pipeline reaches the WRONG verdict.
                         CLEAN : the naive pipeline reaches the RIGHT verdict (a control
                                 that fools the naive pipeline is not a clean control).
G2  the fault is fair    the reference pipeline flags the fault iff the variant is faulty,
                         reaches the true verdict, and lands within tolerance of the
                         true effect.
G3  no giveaway          structure is identical across variants (same n per group, random
                         subject tokens, shuffled order). Non-target differences (e.g. age
                         shift that comes with real high-motion children) are recorded,
                         not hidden, so they can be audited.

Do not edit this file from a fault-generating agent. Changes to the gates are changes to
the benchmark's definition and need human review.
"""
from __future__ import annotations

import re

TOL_SE_MULT = 2.0


def detected(verdict: dict, concern_regex: str) -> bool:
    """The detection response used for signal-detection scoring."""
    pat = re.compile(concern_regex, re.I)
    return any(pat.search(str(c.get("issue", ""))) and bool(c.get("affects_conclusion"))
               for c in verdict.get("concerns", []))


def check(variant: str, truth: dict, naive: dict, ref: dict, sub_table, fault) -> dict:
    tol = TOL_SE_MULT * float(ref["effect_se"])
    g = {}
    if variant == "faulty":
        g["G1_naive_fooled"] = naive["claim_supported"] != truth["supported"]
        g["G2_ref_flags"] = detected(ref, fault.concern_regex)
    else:
        g["G1_naive_correct"] = naive["claim_supported"] == truth["supported"]
        g["G2_ref_no_false_alarm"] = not detected(ref, fault.concern_regex)
    g["G2_ref_true_verdict"] = ref["claim_supported"] == truth["supported"]
    g["G2_ref_within_tol"] = abs(ref["effect_estimate"] - truth["effect"]) <= tol
    counts = sub_table.group.value_counts().to_dict()
    g["G3_sizes"] = (counts.get("child", 0) == fault.n_child and
                     counts.get("adult", 0) == fault.n_adult)
    return {"pass": all(g.values()), "gates": g, "recovery_tol": tol}
