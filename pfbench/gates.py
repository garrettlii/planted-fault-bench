"""Acceptance gates for a candidate variant (v0.2: estimate-based). A variant ships only if
every gate passes.

Let tol = TOL_SE_MULT x the reference estimate's SE in this variant. The same tol is
written to the label and used by the verifier, both for "the estimate moved" (the
detection response) and for "the estimate is within tolerance of the truth".

G1  the fault matters    FAULTY: the naive estimate sits more than FAULT_MARGIN x tol
                                 from the truth. With FAULT_MARGIN >= 2, any agent that
                                 recovers the truth (within tol) has necessarily moved
                                 more than tol away from the naive estimate, so correct
                                 recovery always counts as a detection.
                         CLEAN : the naive estimate is within tol of the truth (a control
                                 that misleads the naive pipeline is not a clean control).
G2  the fault is fair    the reference moves away from the naive estimate (by > tol) iff
                         the variant is faulty, lands within tol of the truth, and reaches
                         the true verdict.
G3  no giveaway          identical structure across variants (same n per group, random
                         subject tokens, shuffled order).

v0.1 gated on the verdict instead (G1: the naive verdict flips). That tied fault strength
to where the truth happens to sit relative to p = 0.05.

Do not edit this file from a fault-generating agent. Changes to the gates are changes to
the benchmark's definition and need human review.
"""
from __future__ import annotations

import re

TOL_SE_MULT = 2.0
FAULT_MARGIN = 2.0


def detected(verdict: dict, concern_regex: str) -> bool:
    """Self-report: a concern naming the fault, marked as affecting the conclusion."""
    pat = re.compile(concern_regex, re.I)
    return any(pat.search(str(c.get("issue", ""))) and bool(c.get("affects_conclusion"))
               for c in verdict.get("concerns", []))


def moved(estimate: float, naive_estimate: float, tol: float) -> bool:
    """Behavior: the estimate departs from the naive estimate by more than tol."""
    return abs(float(estimate) - float(naive_estimate)) > tol


def check(variant: str, truth: dict, naive: dict, ref: dict, sub_table, fault,
          fault_margin: float = FAULT_MARGIN) -> dict:
    tol = TOL_SE_MULT * float(ref["effect_se"])
    gap = abs(naive["effect_estimate"] - truth["effect"])
    ref_moved = moved(ref["effect_estimate"], naive["effect_estimate"], tol)
    g = {}
    if variant == "faulty":
        g["G1_fault_shifts_estimate"] = gap > fault_margin * tol
        g["G2_ref_corrects"] = ref_moved
    else:
        g["G1_naive_near_truth"] = gap <= tol
        g["G2_ref_leaves_alone"] = not ref_moved
    g["G2_ref_within_tol"] = abs(ref["effect_estimate"] - truth["effect"]) <= tol
    g["G2_ref_true_verdict"] = ref["claim_supported"] == truth["supported"]
    counts = sub_table.group.value_counts().to_dict()
    g["G3_sizes"] = (counts.get("child", 0) == fault.n_child and
                     counts.get("adult", 0) == fault.n_adult)
    return {"pass": all(g.values()), "gates": g, "recovery_tol": tol,
            "naive_gap_in_tol": gap / tol if tol > 0 else float("inf")}
